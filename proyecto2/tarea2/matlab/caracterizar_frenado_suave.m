function resultado = caracterizar_frenado_suave
% Analiza solo las nuevas capturas de veinte segundos del montaje actual.
% La corrida libre estima discrepancia con el modelo anterior, no torque.
carpeta=fileparts(mfilename('fullpath'));
raiz=fullfile(carpeta,'..','capturas','escritorio','reales');
angulos=[35 34 36 37 38 45];
ids={ ...
    {'20261127_223742_465772','20261127_223837_077784','20261127_223932_387862'}, ...
    {'20261127_224029_410591','20261127_224130_738496', ...
     '20261127_233312_551495','20261127_233407_607995#ensayo=33', ...
     '20261127_233407_607995#ensayo=34','20261127_233951_894077'}, ...
    {'20261127_224232_172529'}, ...
    {'20261127_224412_621615'}, ...
    {'20261127_224513_379441'}, ...
    {'20261127_224621_377018'}};
grupos=struct('angulo',{},'capturas',{});
for k=1:numel(angulos)
    rutas=cellfun(@(id) fullfile(raiz,id),ids{k},'UniformOutput',false);
    grupos(k)=struct('angulo',angulos(k),'capturas',{rutas});
end
opciones=struct('permitirParciales',false,'permitirExploratorios',true, ...
    'permitirAporteNegativo',true,'salida', ...
    fullfile(carpeta,'resultados_reales','frenado_suave_20s'));
resultado=caracterizar_angulos_freno(grupos,opciones);
fprintf('A 35 grados hay una comprobacion reservada y a 34 hay cuatro. Los demas angulos son exploratorios.\n');
fprintf('45 grados es la referencia libre nueva. Su c diagnostica diferencias con el modelo libre anterior.\n');
fprintf('Las pruebas anteriores de seis segundos no se mezclaron con estas capturas.\n');
end
